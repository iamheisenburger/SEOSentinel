// Packs blog-kit/*.js into convex/lib/blogKitSources.ts, the bytes Pentra commits when it adds a blog to a customer's
// Next.js site. Run after editing blog-kit/: node scripts/blog-kit-sources.mjs (tests fail when the two differ).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "blog-kit");
const files = fs.readdirSync(dir).filter((name) => name.endsWith(".js")).sort();
const body = files.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(fs.readFileSync(path.join(dir, name), "utf8"))},`).join("\n");
const out = `// Generated by scripts/blog-kit-sources.mjs from blog-kit/. Do not edit by hand.\nexport const BLOG_KIT_SOURCES: Record<string, string> = {\n${body}\n};\n`;
fs.writeFileSync(path.join(root, "convex/lib/blogKitSources.ts"), out);
console.log(`blog kit: ${files.length} files packed`);
